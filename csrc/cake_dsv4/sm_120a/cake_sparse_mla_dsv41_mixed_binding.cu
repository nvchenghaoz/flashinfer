  args.out_lse = static_cast<float*>(out_lse.data_ptr());
  args.mid_out = mid_out_ptr;
  args.mid_lse = mid_lse_ptr;
  args.topk = static_cast<int>(topk);
  args.extra_topk = static_cast<int>(extra_topk);
  args.page_size = static_cast<int>(page_size);
